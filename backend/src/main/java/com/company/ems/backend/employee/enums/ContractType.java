package com.company.ems.backend.employee.enums;

/**
 * Contract type enumeration
 * Defines the type of employment contract
 */
public enum ContractType {
    /**
     * Full-time permanent employee
     */
    FULL_TIME,

    /**
     * Part-time employee
     */
    PART_TIME,

    /**
     * Fixed-term contract employee
     */
    CONTRACT,

    /**
     * Intern or trainee
     */
    INTERN,

    /**
     * External consultant
     */
    CONSULTANT,

    /**
     * Temporary worker
     */
    TEMPORARY
}
