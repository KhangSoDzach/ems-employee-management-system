package com.company.ems.backend.leave.enums;

/**
 * Leave type enumeration
 * Defines various types of leave that employees can apply for
 */
public enum LeaveType {
    /**
     * Annual/Vacation leave
     */
    ANNUAL,

    /**
     * Sick leave
     */
    SICK,

    /**
     * Personal leave
     */
    PERSONAL,

    /**
     * Unpaid leave
     */
    UNPAID,

    /**
     * Emergency leave
     */
    EMERGENCY,

    /**
     * Maternity leave
     */
    MATERNITY,

    /**
     * Paternity leave
     */
    PATERNITY,

    /**
     * Bereavement leave
     */
    BEREAVEMENT,

    /**
     * Study leave
     */
    STUDY,

    /**
     * Sabbatical leave
     */
    SABBATICAL,

    /**
     * Compensatory time off
     */
    COMPENSATORY
}
